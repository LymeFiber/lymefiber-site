// Post-build: write dist/_redirects from src/data/redirects.yaml and settings,
// and the same rules as a module for the Pages middleware (functions/_middleware.js).
import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from 'yaml';
import { renderRedirects } from './lib/redirects.mjs';

const rules = parse(readFileSync('src/data/redirects.yaml', 'utf8')).redirects ?? [];
const settings = parse(readFileSync('src/data/settings.yaml', 'utf8'));
const text = renderRedirects(rules, settings);
writeFileSync('dist/_redirects', text);
writeFileSync(
  'functions/_lib/rules.generated.js',
  `// Generated by scripts/gen-redirects.mjs from src/data/redirects.yaml. Do not edit.\nexport default ${JSON.stringify(text)};\n`,
);
console.log(`_redirects: ${rules.length} rules`);
